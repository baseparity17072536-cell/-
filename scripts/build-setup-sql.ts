// Build ONE SQL file that installs the whole system into an empty hosted PostgreSQL
// (e.g. paste into Supabase → SQL Editor → Run). No database password has to leave the owner's hands.
//
//   npx tsx scripts/build-setup-sql.ts --out <file.sql> --host mu-beryl-23.vercel.app [--host other] [--owner owner@hotel.com]
//
// It runs the real migrations + seed on a throw-away local PostgreSQL, then exports the result.
// The output contains the new app-role password and owner password hash: never commit it.
import { randomBytes } from "node:crypto";
import { mkdtemp, readFile, readdir, rm, writeFile } from "node:fs/promises";
import net from "node:net";
import os from "node:os";
import path from "node:path";
import EmbeddedPostgres from "embedded-postgres";
import pg from "pg";
import { runSeed } from "../db/seed";
import { createDatabaseIfMissing, migrateUp, urlFor } from "../db/tooling";

const args = process.argv.slice(2);
const opt = (k: string) => args.flatMap((a, i) => (a === `--${k}` ? [args[i + 1]] : []));
const out = opt("out")[0];
const hosts = opt("host").map((h) => h.trim().toLowerCase());
const ownerEmail = opt("owner")[0] ?? "owner@fahtalay.local";
if (!out || !hosts.length) {
  console.error("usage: tsx scripts/build-setup-sql.ts --out <file.sql> --host <domain> [--host <domain>] [--owner <email>]");
  process.exit(1);
}

const alnum = (n: number) => {
  const chars = "ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz23456789";
  return Array.from(randomBytes(n), (b) => chars[b % chars.length]).join("");
};
const appPassword = alnum(32);
const ownerPassword = `Ft-${alnum(12)}7`;
const appSecret = randomBytes(32).toString("base64url");

function freePort() {
  return new Promise<number>((resolve, reject) => {
    const s = net.createServer();
    s.once("error", reject);
    s.listen(0, "127.0.0.1", () => {
      const p = (s.address() as net.AddressInfo).port;
      s.close(() => resolve(p));
    });
  });
}

// insert order respects foreign keys
const DATA_TABLES = [
  "tenants", "tenant_domains", "users", "memberships", "properties", "room_types", "room_type_images", "rooms",
  "rate_plans", "price_rules", "daily_rates",
];

async function main() {
  const dir = await mkdtemp(path.join(os.tmpdir(), "fahtalay-setup-"));
  const port = await freePort();
  const adminPw = alnum(20);
  const server = new EmbeddedPostgres({
    databaseDir: dir, port, user: "postgres", password: adminPw, persistent: true,
    initdbFlags: ["--encoding=UTF8", "--locale=C"], onLog: () => {}, onError: () => {},
  });
  await server.initialise();
  await server.start();
  try {
    const base = { host: "localhost", port, user: "postgres", password: adminPw };
    await createDatabaseIfMissing(urlFor(base, "postgres"), "setup");
    const url = urlFor(base, "setup");
    await migrateUp(url);
    const { tenantId } = await runSeed(url, { ownerEmail, ownerPassword, hosts, importLegacy: false });

    const c = new pg.Client({ connectionString: url });
    await c.connect();
    const dataSql: string[] = [];
    for (const t of DATA_TABLES) {
      const json = (await c.query(`SELECT coalesce(json_agg(x), '[]'::json)::text AS j FROM ${t} x`)).rows[0].j as string;
      if (json === "[]") continue;
      if (json.includes("$seed$")) throw new Error("unexpected delimiter in data");
      dataSql.push(`INSERT INTO ${t} SELECT * FROM json_populate_recordset(NULL::${t}, $seed$${json}$seed$);`);
    }
    await c.end();

    const migDir = path.join(import.meta.dirname, "..", "db", "migrations");
    const versions = (await readdir(migDir)).filter((f) => f.endsWith(".up.sql")).map((f) => f.replace(/\.up\.sql$/, "")).sort();
    const migrations: string[] = [];
    for (const v of versions) {
      migrations.push(`-- ===== migration ${v} =====`, await readFile(path.join(migDir, `${v}.up.sql`), "utf8"),
        `INSERT INTO schema_migrations (version) VALUES ('${v}');`);
    }

    const sql = [
      "-- FahTalay Booking Engine — full installation script (generated by scripts/build-setup-sql.ts)",
      "-- Run ONCE on an EMPTY database (Supabase: SQL Editor → paste → Run). Everything runs in one transaction.",
      "-- CONTAINS A PASSWORD — do not commit or share this file. Delete it after installation.",
      "BEGIN;",
      "CREATE TABLE IF NOT EXISTS schema_migrations (version text PRIMARY KEY, applied_at timestamptz NOT NULL DEFAULT now());",
      ...migrations,
      "-- ===== application login role (RLS always applies to it) =====",
      `CREATE ROLE fahtalay_app LOGIN NOSUPERUSER NOBYPASSRLS PASSWORD '${appPassword}';`,
      "GRANT app_runtime TO fahtalay_app;",
      "-- ===== initial data =====",
      `SELECT set_config('app.tenant_id', '${tenantId}', true);`,
      ...dataSql,
      "COMMIT;",
      "SELECT 'installed' AS status, (SELECT string_agg(name, ', ') FROM tenants) AS hotel, (SELECT string_agg(host, ', ') FROM tenant_domains) AS domains, (SELECT count(*) FROM schema_migrations) AS migrations;",
      "",
    ].join("\n");
    await writeFile(out, sql, "utf8");

    console.log(JSON.stringify({ file: out, appPassword, ownerEmail, ownerPassword, appSecret, hosts }, null, 2));
  } finally {
    await server.stop().catch(() => {});
    await rm(dir, { recursive: true, force: true, maxRetries: 20, retryDelay: 250 }).catch(() => {});
  }
}

main().then(
  () => process.exit(0), // embedded-postgres can leave handles open on Windows
  (e) => {
    console.error(e);
    process.exit(1);
  },
);
