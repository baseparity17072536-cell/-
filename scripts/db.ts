// Development database CLI.
//   npm run db:start     start local PostgreSQL (embedded, data in .pgdata/) and keep it running
//   npm run db:migrate   apply pending migrations + ensure the app login role
//   npm run db:rollback  roll back the latest migration
//   npm run db:seed      seed FahTalay tenant (rooms from the prototype, owner account, imported bookings)
//
// Connection settings live in .env.development.local (created on first db:start, never committed).
import { randomBytes } from "node:crypto";
import { existsSync } from "node:fs";
import { writeFile } from "node:fs/promises";
import path from "node:path";
import EmbeddedPostgres from "embedded-postgres";
import { createDatabaseIfMissing, ensureAppLogin, migrateDown, migrateUp, urlFor } from "../db/tooling";

const ROOT = path.resolve(import.meta.dirname, "..");
const ENV_FILE = path.join(ROOT, ".env.development.local");
const PG_DIR = path.join(ROOT, ".pgdata");
const PORT = 54329;
const DB_NAME = "fahtalay_dev";
const APP_USER = "fahtalay_app";

function loadEnv() {
  for (const f of [".env.local", ".env.development.local"]) {
    const p = path.join(ROOT, f);
    if (existsSync(p)) process.loadEnvFile(p);
  }
}

async function ensureEnvFile() {
  if (existsSync(ENV_FILE)) return;
  const admin = randomBytes(18).toString("base64url");
  const app = randomBytes(18).toString("base64url");
  const sessionSecret = randomBytes(32).toString("base64url");
  await writeFile(
    ENV_FILE,
    [
      "# Generated by scripts/db.ts for LOCAL DEVELOPMENT ONLY. Never commit.",
      `PGLOCAL_ADMIN_PASSWORD=${admin}`,
      `DATABASE_ADMIN_URL=${urlFor({ host: "localhost", port: PORT, user: "postgres", password: admin }, DB_NAME)}`,
      `DATABASE_APP_PASSWORD=${app}`,
      `DATABASE_URL=${urlFor({ host: "localhost", port: PORT, user: APP_USER, password: app }, DB_NAME)}`,
      `APP_SECRET=${sessionSecret}`,
      "",
    ].join("\n"),
    "utf8",
  );
  console.log("created .env.development.local");
}

function required(name: string) {
  const v = process.env[name];
  if (!v) throw new Error(`${name} is not set (run "npm run db:start" first)`);
  return v;
}

async function start() {
  await ensureEnvFile();
  loadEnv();
  const pgServer = new EmbeddedPostgres({
    databaseDir: PG_DIR,
    port: PORT,
    user: "postgres",
    password: required("PGLOCAL_ADMIN_PASSWORD"),
    authMethod: "scram-sha-256",
    persistent: true,
    initdbFlags: ["--encoding=UTF8", "--locale=C"],
    onLog: () => {},
  });
  if (!existsSync(path.join(PG_DIR, "PG_VERSION"))) await pgServer.initialise();
  await pgServer.start();
  const serverUrl = urlFor({ host: "localhost", port: PORT, user: "postgres", password: required("PGLOCAL_ADMIN_PASSWORD") }, "postgres");
  await createDatabaseIfMissing(serverUrl, DB_NAME);
  console.log(`PostgreSQL running on localhost:${PORT} (database ${DB_NAME}). Press Ctrl+C to stop.`);
  const stop = async () => {
    await pgServer.stop();
    process.exit(0);
  };
  process.on("SIGINT", stop);
  process.on("SIGTERM", stop);
  await new Promise(() => {});
}

async function migrate() {
  loadEnv();
  const applied = await migrateUp(required("DATABASE_ADMIN_URL"), console.log);
  await ensureAppLogin(required("DATABASE_ADMIN_URL"), APP_USER, required("DATABASE_APP_PASSWORD"));
  console.log(applied.length ? `done (${applied.length} applied)` : "already up to date");
}

async function rollback() {
  loadEnv();
  const v = await migrateDown(required("DATABASE_ADMIN_URL"), console.log);
  console.log(v ? "done" : "nothing to roll back");
}

async function seed() {
  loadEnv();
  const { runSeed } = await import("../db/seed");
  await runSeed(required("DATABASE_ADMIN_URL"));
}

const commands: Record<string, () => Promise<void>> = { start, migrate, rollback, seed };
const cmd = process.argv[2] ?? "";
if (!commands[cmd]) {
  console.error(`usage: tsx scripts/db.ts <${Object.keys(commands).join("|")}>`);
  process.exit(1);
}
commands[cmd]().catch((e) => {
  console.error(e);
  process.exit(1);
});
